"""Regenerate src/ai_service/db_models.py from the live database (sqlacodegen).

Run after applying a migration, from ai-service/:
    uv run python scripts/gen_models.py

The SQL files in db/migrations/ own the schema; this script only reads it, so the Python
classes can never drift from the real tables.
"""

import subprocess
import sys
from pathlib import Path

from ai_service.config import get_settings

# Only the tables the Python service uses. The Go API maps its own tables with sqlc.
TABLES = ["content_facts"]

OUT = Path(__file__).resolve().parents[1] / "src" / "ai_service" / "db_models.py"
HEADER = '''"""GENERATED by scripts/gen_models.py from the live database. Do not edit by hand.

To change a table: add a migration in db/migrations/, apply it, then rerun the script.
"""

'''


def main() -> int:
    url = get_settings().database_url
    result = subprocess.run(
        [sys.executable, "-m", "sqlacodegen", "--generator", "sqlmodels", "--tables", ",".join(TABLES), url],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        print(result.stderr, file=sys.stderr)
        return result.returncode
    # sqlacodegen prints status lines (e.g. "Using pgvector 0.5.1") before the code: keep from the first import.
    lines = result.stdout.splitlines()
    start = next(i for i, line in enumerate(lines) if line.startswith(("import ", "from ")))
    OUT.write_text(HEADER + "\n".join(lines[start:]) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({', '.join(TABLES)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
